import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { z } from 'zod';
import { NFR_METHOD, recommendNfr } from '../services/nfr-engine.js';

const label = z.object({ module: z.string(), operation: z.string() });
const tags = z.array(z.string());
const profile = z.object({
  classificationId: z.string(), storyId: z.string(), project: z.string(), text: z.string(),
  taxonomyVersion: z.string(), reviewStatus: z.string(), labels: z.array(label),
  projectProfile: z.object({
    taxonomyVersion: z.string(), platforms: tags, applicationDomains: tags,
    objective: z.enum(['', 'product', 'prototype']), architectures: tags,
    technologies: z.object({ languages: tags, frameworks: tags, apis: tags, dataPersistence: tags })
  }),
  tasks: z.array(z.object({ category: z.string() })),
  nfrs: z.array(z.object({ type: z.string(), attribute: z.string(), sentence: z.string() }))
});
const referenceSchema = z.object({
  schemaVersion: z.literal(1), kind: z.literal('reconstructed_demonstration'),
  method: z.string(), notes: z.array(z.string()).min(1),
  profiles: z.record(z.string(), profile),
  cases: z.array(z.object({
    id: z.string().min(1), targetId: z.string(), historyIds: z.array(z.string()),
    labelIndex: z.number().int(), expected: z.record(z.string(), z.unknown())
  })).min(1)
});
const manifestSchema = z.object({
  schemaVersion: z.literal(1), method: z.string(), referenceFile: z.literal('reference.json'),
  referenceSha256: z.string().regex(/^[a-f0-9]{64}$/)
});

/** Read-only replay: expected results must be reviewed, never regenerated by this check. */
export function checkNfrBaseline(referenceText: string, manifestText: string) {
  const manifest = manifestSchema.parse(JSON.parse(manifestText));
  // Git may use CRLF on Windows; the captured snapshot defines its text hash with LF.
  const digest = createHash('sha256').update(referenceText.replace(/\r\n/g, '\n')).digest('hex');
  assert.equal(digest, manifest.referenceSha256, 'O hash da referência RNF divergiu do manifesto.');
  const reference = referenceSchema.parse(JSON.parse(referenceText));
  assert.equal(reference.method, manifest.method, 'Método da referência difere do manifesto.');
  assert.equal(NFR_METHOD, reference.method, 'Use um adaptador do método histórico para preservar esta referência.');
  const ids = new Set<string>();
  return reference.cases.map(item => {
    assert.ok(!ids.has(item.id), `Cenário duplicado: ${item.id}`);
    ids.add(item.id);
    const target = reference.profiles[item.targetId];
    assert.ok(target, `Alvo ausente em ${item.id}`);
    const history = item.historyIds.map(id => {
      const candidate = reference.profiles[id];
      assert.ok(candidate, `Candidato ${id} ausente em ${item.id}`);
      return candidate;
    });
    const before = structuredClone({ target, history });
    const result = recommendNfr(target, history, item.labelIndex);
    assert.deepEqual(result, item.expected, `Regressão RNF: ${item.id}`);
    assert.deepEqual({ target, history }, before, `A execução alterou a entrada: ${item.id}`);
    assert.deepEqual(recommendNfr(target, [...history].reverse(), item.labelIndex), item.expected,
      `Resultado depende da ordem da base: ${item.id}`);
    assert.deepEqual({ target, history }, before, `A repetição alterou a entrada: ${item.id}`);
    return { id: item.id, status: result.status, neighbor: result.neighbor?.classificationId ?? null };
  });
}
